import pandas as pd, numpy as np, os
from sklearn.metrics import average_precision_score
from catboost import CatBoostClassifier
from lightgbm import LGBMClassifier
from xgboost import XGBClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.preprocessing import StandardScaler

ROOT = r'C:\Users\dhl\data\thesis\thesis'
DATA = os.path.join(ROOT, 'Data', 'Warehouse_As_Of')

df = pd.read_csv(os.path.join(DATA, 'H0_Filing_Master_Enriched.csv'), low_memory=False)
df['year'] = pd.to_numeric(df['year'], errors='coerce')
df = df.dropna(subset=['year', 'is_protested']).sort_values('year')

drop_cols = ['is_protested', 'case_number', 'organized_opposition', 'year', 'date', 'application_start_date', 'final_date']
future_features = ['staff_recommendation_cat', 'agenda_text_raw', 'spatial_contagion_1yr', 'spatial_contagion_3yr']
X_raw = df.drop(columns=[c for c in (drop_cols + future_features) if c in df.columns], errors='ignore').select_dtypes(include=[np.number]).fillna(0)
y = df['is_protested'].values
years = df['year'].values

anchors = [2018, 2019, 2020, 2021, 2022, 2023, 2024]
eval_years = [2018, 2019, 2020, 2021, 2022, 2023, 2024]

drift_results = []
for anchor in anchors:
    train_mask = years < anchor
    if train_mask.sum() < 50: continue
    X_train_raw, y_train = X_raw.values[train_mask], y[train_mask]
    scaler = StandardScaler()
    X_train_sc = scaler.fit_transform(X_train_raw)

    models = {
        'CatBoost': CatBoostClassifier(iterations=100, depth=6, verbose=0, random_seed=42),
        'XGBoost': XGBClassifier(n_estimators=100, max_depth=6, random_state=42, eval_metric='logloss'),
        'Random Forest': RandomForestClassifier(n_estimators=100, max_depth=6, random_state=42),
        'Logistic (L2)': LogisticRegression(class_weight='balanced', random_state=42)
    }

    for name, m in models.items():
        if name == 'Logistic (L2)': m.fit(X_train_sc, y_train)
        else: m.fit(X_train_raw, y_train)

    for test_year in eval_years:
        if test_year < anchor: continue
        test_mask = years == test_year
        if test_mask.sum() < 5 or y[test_mask].sum() < 1: continue
            
        X_test_raw, y_test = X_raw.values[test_mask], y[test_mask]
        X_test_sc = scaler.transform(X_test_raw)
        
        for name, m in models.items():
            p = m.predict_proba(X_test_sc if name == 'Logistic (L2)' else X_test_raw)[:, 1]
            base_rate = y_test.sum() / len(y_test)
            prauc = average_precision_score(y_test, p)
            lift = prauc / base_rate
            family = 'Linear' if name == 'Logistic (L2)' else 'Trees'
            drift_results.append({
                'Family': family, 'Model': name, 'Anchor': f'Pre-{anchor}',
                'Evaluate_Year': test_year, 'PRAUC': prauc, 'Lift': lift
            })

results_df = pd.DataFrame(drift_results)

pivot_p = results_df.groupby(['Family', 'Anchor', 'Evaluate_Year'])['PRAUC'].max().reset_index()
pivot_mat_p = pivot_p.pivot_table(index='Family', columns=['Anchor', 'Evaluate_Year'], values='PRAUC')
winners_p = pivot_mat_p.idxmax()

pivot_l = results_df.groupby(['Family', 'Anchor', 'Evaluate_Year'])['Lift'].max().reset_index()
pivot_mat_l = pivot_l.pivot_table(index='Family', columns=['Anchor', 'Evaluate_Year'], values='Lift')
winners_l = pivot_mat_l.idxmax()

tex_lines = [
    r'\begin{table}[htbp]', r'\centering',
    r'\caption[Temporal Drift (Max-of-Family)]{\textbf{Max-of-Family architectural dominance.} Maximum absolute PR-AUC and PR-AUC Lift generated by either the linear baseline or the non-linear tree ensembles, highlighting the structural boundary of architectural capacity under domain shift.}',
    r'\label{tab:temporal_drift_family}', r'\resizebox{\textwidth}{!}{%',
    r'\begin{tabular}{l' + 'c'*len(eval_years) + '}', r'\toprule',
    r'\textbf{Anchor Training} & ' + ' & '.join(['\\textbf{' + str(y) + '}' for y in eval_years]) + r' \\',
    r'\midrule',
    r'\multicolumn{8}{c}{\textbf{Panel A: Maximum Absolute PR-AUC}} \\',
    r'\midrule'
]

for anchor in [f'Pre-{y}' for y in anchors]:
    row_sub = pivot_p[pivot_p['Anchor'] == anchor]
    if len(row_sub) == 0: continue
    
    r = []
    for test_year in eval_years:
        if test_year < int(anchor[-4:]): r.append("---")
        else:
            win_fam = winners_p.loc[(anchor, test_year)] if (anchor, test_year) in winners_p.index else None
            if win_fam is None:
                r.append("---")
            else:
                max_val = pivot_mat_p.loc[win_fam, (anchor, test_year)]
                r.append(f"{max_val:.3f} ({win_fam})")
    tex_lines.append(f"{anchor} & " + " & ".join(r) + r" \\")

tex_lines.extend([
    r'\midrule',
    r'\multicolumn{8}{c}{\textbf{Panel B: Maximum Relative PR-AUC Lift}} \\',
    r'\midrule'
])

for anchor in [f'Pre-{y}' for y in anchors]:
    row_sub = pivot_l[pivot_l['Anchor'] == anchor]
    if len(row_sub) == 0: continue
    
    r = []
    for test_year in eval_years:
        if test_year < int(anchor[-4:]): r.append("---")
        else:
            win_fam = winners_l.loc[(anchor, test_year)] if (anchor, test_year) in winners_l.index else None
            if win_fam is None:
                r.append("---")
            else:
                max_val = pivot_mat_l.loc[win_fam, (anchor, test_year)]
                r.append(f"{max_val:.2f} ({win_fam})")
    tex_lines.append(f"{anchor} & " + " & ".join(r) + r" \\")

tex_lines.extend([r'\bottomrule', r'\end{tabular}%', r'}', r'\end{table}'])

OUT_DIR = os.path.join(ROOT, 'Thesis_Draft', 'Draft_v1', 'Tables')
with open(os.path.join(OUT_DIR, 'temporal_drift_family.tex'), 'w') as f:
    f.write('\n'.join(tex_lines))
